export function buildTemplateFromProject(params: {
  project: Project;
  tasks: TaskCard[];
  milestones: Milestone[];
  templateName: string;
  category: string;
}): ProjectTemplate {
  return {
    id: `custom_${Date.now()}`,
    name: params.templateName.trim().slice(0, 80) || `${params.project.name} Template`,
    category: params.category.trim().slice(0, 40) || 'Custom',
    description: params.project.description || `Custom template derived from ${params.project.name}`,
    suggestedKey: params.project.key,
    isCustom: true,
    milestones: params.milestones.slice(0, 10).map((m) => ({
      name: m.name,
      description: m.description,
      dueOffsetDays: 7,
    })),
    tasks: params.tasks.slice(0, 25).map((t) => ({
      title: t.title,
      description: t.description,
      status: t.status,
      priority: t.priority,
      tags: t.tags ?? [],
      estimatedMinutes: t.estimatedMinutes ?? 0,
      subtasks: (t.subtasks ?? []).map((s) => s.title),
      dueOffsetDays: 5,
    })),
  };
}
